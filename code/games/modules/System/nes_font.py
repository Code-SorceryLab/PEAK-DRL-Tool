@lru_cache(maxsize=512)
def nes_text(text: str, scale: int = 2, color=(255, 255, 255), shadow=None) -> pygame.Surface:
    """text in the 5x7 font, each font pixel a scale x scale block; upper-cased, "*" is the times sign,
    "$" a coin, ">" a menu cursor, unknown characters blank. shadow: a colour for a one-pixel drop shadow. Cached: blit only."""
    text = text.upper()
    off = scale if shadow else 0
    surf = pygame.Surface((max(1, len(text) * 6 - 1) * scale + off, 7 * scale + off), pygame.SRCALPHA)
    for d, colour in ([(off, shadow)] if shadow else []) + [(0, color)]:
        for i, ch in enumerate(text):
            for y, row in enumerate(_GLYPHS.get(ch, ())):
                for x, bit in enumerate(row):
                    if bit == "#":
                        surf.fill(colour, ((i * 6 + x) * scale + d, y * scale + d, scale, scale))
    return surf
